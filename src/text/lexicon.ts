export function isSpelledReading(reading: string): boolean {
  let rest = reading;
  let letters = 0;
  while (rest.length > 0) {
    const name = LETTER_NAMES.find((candidate) => rest.startsWith(candidate));
    if (name === undefined) return false;
    rest = rest.slice(name.length);
    letters += 1;
  }
  return letters >= 2;
}
