const BY_SURFACE: Map<string, LexiconEntry> = new Map<string, LexiconEntry>();
for (const [surface, reading, accent] of ENTRIES) {
  BY_SURFACE.set(surface, { surface, reading, ...(accent === undefined ? {} : { accent }) });
}

export const BUILTIN_LEXICON: ReadonlyMap<string, LexiconEntry> = BY_SURFACE;

export function lookupLexicon(word: string): LexiconEntry | undefined {
  return BY_SURFACE.get(word.toLowerCase());
}

